from __future__ import annotations

import argparse
import hashlib
import struct
import sys
import unicodedata
import zlib
from collections import Counter
from pathlib import Path

MAGIC = b"EPY1"
VERSION = 1
BLOCK_SHIFT = 5
BLOCK_SIZE = 1 << BLOCK_SHIFT
HEADER = struct.Struct("<4sBBHI")
INDEX = struct.Struct("<HH")
UNIHAN_VERSION = "16.0.0"
UNICODE_LICENSE = "Unicode License v3"
ASSET_BUDGET = 18000


class PinyinTable:
    def __init__(self, records, syllables):
        self._records = dict(records)
        self._syllables = tuple(syllables)

    def syllable(self, codepoint):
        return self._records.get(codepoint)

    def hanzi_count(self):
        return sum(1 for codepoint in self._records if 0x4E00 <= codepoint <= 0x9FFF)


