KATAKANA_ONLY = (("ヷ", "va"), ("ヸ", "vi"), ("ヹ", "ve"), ("ヺ", "vo"))


def kana_readings():
    readings = {}
    for character, syllable in HIRAGANA:
        readings[ord(character)] = syllable
        code = ord(character)
        if 0x3041 <= code <= 0x3096:
            readings[code + 0x60] = syllable
    readings[ord("ー")] = "-"
    for character, syllable in KATAKANA_ONLY:
        readings[ord(character)] = syllable
    return readings


def gb2312_hanzi():
    characters = []
    for first in range(0xA1, 0xF8):
        for second in range(0xA1, 0xFF):
            try:
                character = bytes((first, second)).decode("gb2312")
            except UnicodeDecodeError:
                continue
            if "\u4e00" <= character <= "\u9fff":
                characters.append(character)
    return characters


def plain_reading(reading):
    decomposed = unicodedata.normalize("NFD", reading)
    decomposed = decomposed.replace("u\u0308", "v").replace("U\u0308", "V")
    stripped = "".join(part for part in decomposed if not unicodedata.combining(part))
    return stripped.lower()


def unihan_readings(path):
    readings = {}
    for line in path.read_text(encoding="utf-8").splitlines():
        if not line or line.startswith("#"):
            continue
        fields = line.split("\t")
        if len(fields) != 3 or fields[1] != "kMandarin":
            continue
        code = int(fields[0][2:], 16)
        values = [plain_reading(value) for value in fields[2].split()]
        values = [value for value in values if value.isascii() and value.isalpha()]
        if values:
            readings[code] = values
    return readings


def extract(unihan, output, version=UNIHAN_VERSION):
    readings = unihan_readings(unihan)
    entries = {}
    for character in gb2312_hanzi():
        code = ord(character)
        if code not in readings:
            raise SystemExit(f"no kMandarin reading for U+{code:04X}")
        entries[code] = readings[code][0]
    for code, syllable in kana_readings().items():
        entries[code] = syllable
    lines = [
        f"# source: Unihan {version}",
        f"# license: {UNICODE_LICENSE}",
        "# generated by tools/pinyin_table.py extract",
    ]
    for code in sorted(entries):
        lines.append(f"U+{code:04X}\t{entries[code]}")
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {len(entries):,} entries to {output}")


def parse_source(path):
    entries = {}
    for line in path.read_text(encoding="utf-8").splitlines():
        if not line or line.startswith("#"):
            continue
        fields = line.split("\t")
        if len(fields) != 2 or not fields[0].startswith("U+"):
            raise ValueError(f"bad source line: {line!r}")
        code = int(fields[0][2:], 16)
        syllable = fields[1]
        if code in entries:
            raise ValueError(f"duplicate U+{code:04X}")
        if not syllable or not all(part.isascii() for part in syllable):
            raise ValueError(f"bad syllable for U+{code:04X}: {syllable!r}")
        entries[code] = syllable
    return entries


def build_bytes(entries):
    records = sorted(entries.items())
    counts = Counter(syllable for _, syllable in records)
    syllables = sorted(counts, key=lambda syllable: (-counts[syllable], syllable))
    codes = {syllable: index for index, syllable in enumerate(syllables)}
    decoded = b"".join(struct.pack("<HH", code, codes[syllable]) for code, syllable in records)
    header = HEADER.pack(MAGIC, VERSION, BLOCK_SHIFT, len(records), zlib.crc32(decoded))
    blocks = [records[index:index + BLOCK_SIZE] for index in range(0, len(records), BLOCK_SIZE)]
    index = bytearray()
    data = bytearray()
    for block in blocks:
        index += INDEX.pack(block[0][0], len(data))
        previous = 0
        for code, syllable in block:
            delta = code - previous
            previous = code
            if delta < 0xFF:
                data.append(delta)
            else:
                data += b"\xff" + struct.pack("<H", delta)
            syllable_code = codes[syllable]
            if syllable_code < 0xFF:
                data.append(syllable_code)
            else:
                data += bytes((0xFF, syllable_code - 0xFF))
    syllable_data = bytearray(struct.pack("<H", len(syllables)))
    for syllable in syllables:
        encoded = syllable.encode("ascii")
        syllable_data += bytes((len(encoded),)) + encoded
    payload = bytes(header) + bytes(index) + bytes(data) + bytes(syllable_data)
    return payload + struct.pack("<I", zlib.crc32(payload))


def decode(data):
    if len(data) < HEADER.size + 4:
        raise ValueError("truncated pinyin header")
    payload_size = len(data) - 4
    expected_asset_crc = struct.unpack_from("<I", data, payload_size)[0]
    if zlib.crc32(data[:payload_size]) != expected_asset_crc:
        raise ValueError("pinyin asset checksum mismatch")
    magic, version, block_shift, count, expected_crc = HEADER.unpack_from(data)
    if magic != MAGIC or version != VERSION or block_shift != BLOCK_SHIFT:
        raise ValueError("bad pinyin header")
    if count == 0:
        raise ValueError("empty pinyin table")
    block_size = 1 << block_shift
    blocks = (count + block_size - 1) // block_size
    index_size = blocks * INDEX.size
    data_start = HEADER.size + index_size
    if data_start > payload_size:
        raise ValueError("truncated pinyin index")
    offsets = []
    for block in range(blocks):
        first, offset = INDEX.unpack_from(data, HEADER.size + block * INDEX.size)
        offsets.append((first, offset))
    records = []
    decoded = bytearray()
    data_end = data_start
    for block, (first, offset) in enumerate(offsets):
        position = data_start + offset
        previous = 0
        for position_in_block in range(block_size):
            record_index = block * block_size + position_in_block
            if record_index >= count:
                break
            if position >= payload_size:
                raise ValueError("truncated pinyin records")
            delta = data[position]
            position += 1
            if delta == 0xFF:
                if position + 2 > payload_size:
                    raise ValueError("truncated pinyin delta")
                delta = struct.unpack_from("<H", data, position)[0]
                position += 2
            code = previous + delta if position_in_block else first
            if position_in_block == 0:
                code = first
            previous = code
            if position >= payload_size:
                raise ValueError("truncated pinyin syllable code")
            syllable_code = data[position]
            position += 1
            if syllable_code == 0xFF:
                if position >= payload_size:
                    raise ValueError("truncated pinyin syllable escape")
                syllable_code = 0xFF + data[position]
                position += 1
            if code > 0xFFFF:
                raise ValueError("pinyin code point out of range")
            records.append((code, syllable_code))
            decoded += struct.pack("<HH", code, syllable_code)
        data_end = max(data_end, position)
    if len(records) != count:
        raise ValueError("pinyin record count mismatch")
    if zlib.crc32(decoded) != expected_crc:
        raise ValueError("pinyin decoded checksum mismatch")
    if data_end + 2 > payload_size:
        raise ValueError("truncated pinyin syllable table")
    syllable_count = struct.unpack_from("<H", data, data_end)[0]
    position = data_end + 2
    syllables = []
    for _ in range(syllable_count):
        if position >= payload_size:
            raise ValueError("truncated pinyin syllable")
        length = data[position]
        position += 1
        if position + length > payload_size:
            raise ValueError("truncated pinyin syllable text")
        syllables.append(data[position:position + length].decode("ascii"))
        position += length
    if any(code >= syllable_count for _, code in records):
        raise ValueError("pinyin syllable index out of range")
    return PinyinTable([(code, syllables[index]) for code, index in records], syllables)


def load(path):
    return decode(Path(path).read_bytes())


def manifest_text(source, asset_bytes, entries):
    source_bytes = source.read_bytes()
    return "\n".join([
        "# Pinyin table",
        "",
        f"- Source: Unicode {UNIHAN_VERSION} Unihan_Readings.txt",
        f"- License: {UNICODE_LICENSE}",
        f"- Hanzi: {sum(1 for code in entries if 0x4E00 <= code <= 0x9FFF):,}",
        f"- Kana: {sum(1 for code in entries if 0x3040 <= code <= 0x30FF):,}",
        f"- Syllables: {len(set(entries.values())):,}",
        f"- Asset bytes: {len(asset_bytes):,}",
        f"- Source SHA-256: {hashlib.sha256(source_bytes).hexdigest()}",
        f"- Asset SHA-256: {hashlib.sha256(asset_bytes).hexdigest()}",
        f"- Decoded CRC32: {struct.unpack_from('<I', asset_bytes, 8)[0]:08x}",
        "",
        "The table is generated from the pinned Unihan extract and is redistributed",
        f"under the {UNICODE_LICENSE}.",
        "",
    ])


def build(source, output, manifest):
    entries = parse_source(source)
    asset_bytes = build_bytes(entries)
    if len(asset_bytes) > ASSET_BUDGET:
        raise SystemExit(f"asset is {len(asset_bytes)} bytes, budget is {ASSET_BUDGET}")
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_bytes(asset_bytes)
    text = manifest_text(source, asset_bytes, entries)
    manifest.write_text(text, encoding="utf-8")
    print(f"wrote {output} ({len(asset_bytes):,} bytes) and {manifest}")


def check(source, asset, manifest):
    entries = parse_source(source)
    expected = build_bytes(entries)
    actual = Path(asset).read_bytes()
    if actual != expected:
        raise SystemExit(f"{asset} is out of date")
    expected_manifest = manifest_text(Path(source), expected, entries)
    if Path(manifest).read_text(encoding="utf-8") != expected_manifest:
        raise SystemExit(f"{manifest} is out of date")
    print(f"{asset} and {manifest} are up to date")


def main():
    parser = argparse.ArgumentParser()
    commands = parser.add_subparsers(dest="command", required=True)
    extract_parser = commands.add_parser("extract")
    extract_parser.add_argument("--unihan", type=Path, required=True)
    extract_parser.add_argument("--output", type=Path, required=True)
    extract_parser.add_argument("--version", default=UNIHAN_VERSION)
    build_parser = commands.add_parser("build")
    build_parser.add_argument("--source", type=Path, required=True)
    build_parser.add_argument("--output", type=Path, required=True)
    build_parser.add_argument("--manifest", type=Path, required=True)
    check_parser = commands.add_parser("check")
    check_parser.add_argument("--source", type=Path, required=True)
    check_parser.add_argument("--asset", type=Path, required=True)
    check_parser.add_argument("--manifest", type=Path, required=True)
    arguments = parser.parse_args()
    if arguments.command == "extract":
        extract(arguments.unihan, arguments.output, arguments.version)
    elif arguments.command == "build":
        build(arguments.source, arguments.output, arguments.manifest)
    else:
        check(arguments.source, arguments.asset, arguments.manifest)
    return 0


if __name__ == "__main__":
    sys.exit(main())
